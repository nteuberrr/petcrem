--  Tablas EXTRA del esquema principal.
--
--  Todo lo de acá NO sale del mapa `SHEETS` (lib/sheets-schema.ts) porque no se
--  accede por `datastore`: son logs y tablas de sistema que usan `getSupabase()`
--  directo. El generador (scripts/generar-schema-sql.ts) las APENDEA al final de
--  supabase/schema-principal.sql — antes vivían pegadas a mano en ese archivo y
--  se PERDÍAN en cada regeneración.
--
--  Al sumar una tabla que no va por datastore, agregarla acá (no al .sql generado).
